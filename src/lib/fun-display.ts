const knownIds = new Set(kaomoji.map((item) => item.id));
export const kaomojiStorageKey = 'qingxia:kaomoji-favorites:v1';
export function parseKaomojiFavorites(raw: string | null): string[] {
  try {
    if (!raw || raw.length > 32768) return [];
    const value: unknown = JSON.parse(raw);
    if (!Array.isArray(value)) return [];
    return [
      ...new Set(value.filter((id): id is string => typeof id === 'string' && knownIds.has(id))),
    ].slice(0, kaomoji.length);
  } catch {
    return [];
  }
}
export function searchKaomoji(query: string, category = '全部', favorites?: readonly string[]) {
  const term = query.trim().toLocaleLowerCase();
  return kaomoji.filter(
    (item) =>
      (category === '全部' || category === item.category) &&
      (!favorites || favorites.includes(item.id)) &&
      (!term ||
        `${item.label} ${item.category} ${item.keywords} ${item.value}`
          .toLocaleLowerCase()
          .includes(term)),
  );
}
